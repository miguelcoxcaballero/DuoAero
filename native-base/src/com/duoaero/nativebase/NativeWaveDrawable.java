package com.duoaero.nativebase;

import android.content.res.Resources;
import android.content.res.TypedArray;
import android.graphics.Bitmap;
import android.graphics.BitmapFactory;
import android.graphics.Canvas;
import android.graphics.ColorFilter;
import android.graphics.Paint;
import android.graphics.PixelFormat;
import android.graphics.Rect;
import android.graphics.RectF;
import android.graphics.drawable.Animatable;
import android.graphics.drawable.Drawable;
import android.os.SystemClock;
import android.util.AttributeSet;
import java.io.IOException;
import org.xmlpull.v1.XmlPullParser;
import org.xmlpull.v1.XmlPullParserException;

/** Experimental transparent, frame-by-frame wave for one original ImageView.
 * The source image is a 4x4 atlas; no frame is generated by moving a still.
 */
public final class NativeWaveDrawable extends Drawable implements Animatable, Runnable {
 private static final int COLUMNS=4, FRAMES=16;
 private static final long FRAME_MS=83;
 private final Paint paint=new Paint(Paint.ANTI_ALIAS_FLAG|Paint.FILTER_BITMAP_FLAG);
 private final Rect source=new Rect();
 private final RectF target=new RectF();
 private Bitmap atlas;
 private int intrinsicWidth=-1,intrinsicHeight=-1;
 private boolean running,initialized;
 private long startedAt,stoppedAt;
 public NativeWaveDrawable(){}
 @Override public void inflate(Resources resources,XmlPullParser parser,AttributeSet attrs,Resources.Theme theme)
   throws XmlPullParserException,IOException {
  super.inflate(resources,parser,attrs,theme);
  TypedArray values=resources.obtainAttributes(attrs,new int[]{android.R.attr.width,android.R.attr.height});
  try{intrinsicWidth=values.getDimensionPixelSize(0,-1);intrinsicHeight=values.getDimensionPixelSize(1,-1);}
  finally{values.recycle();}
  int id=resources.getIdentifier("duoaero_scene_wave","drawable","com.duolingo");
  if(id==0)throw new XmlPullParserException("Wave atlas resource missing");
  BitmapFactory.Options options=new BitmapFactory.Options();options.inScaled=false;
  atlas=BitmapFactory.decodeResource(resources,id,options);
  if(atlas==null||atlas.getWidth()<COLUMNS||atlas.getHeight()<COLUMNS||intrinsicWidth<=0||intrinsicHeight<=0)
   throw new XmlPullParserException("Invalid wave atlas or intrinsic size");
 }
 @Override public void draw(Canvas canvas){
  if(atlas==null)return;
  if(!initialized){initialized=true;start();}
  long frameTime=running?SystemClock.uptimeMillis():stoppedAt;
  int frame=(int)(((frameTime-startedAt)/FRAME_MS)%FRAMES);
  int column=frame%COLUMNS,row=frame/COLUMNS;
  source.set(column*atlas.getWidth()/COLUMNS,row*atlas.getHeight()/COLUMNS,
             (column+1)*atlas.getWidth()/COLUMNS,(row+1)*atlas.getHeight()/COLUMNS);
  Rect bounds=getBounds();float scale=Math.min((float)bounds.width()/source.width(),(float)bounds.height()/source.height());
  float w=source.width()*scale,h=source.height()*scale;
  target.set(bounds.exactCenterX()-w/2f,bounds.exactCenterY()-h/2f,bounds.exactCenterX()+w/2f,bounds.exactCenterY()+h/2f);
  canvas.drawBitmap(atlas,source,target,paint);
 }
 @Override public int getIntrinsicWidth(){return intrinsicWidth;}
 @Override public int getIntrinsicHeight(){return intrinsicHeight;}
 @Override public void setAlpha(int alpha){paint.setAlpha(alpha);invalidateSelf();}
 @Override public void setColorFilter(ColorFilter filter){paint.setColorFilter(filter);invalidateSelf();}
 @Override public int getOpacity(){return PixelFormat.TRANSLUCENT;}
 @Override public void start(){if(!running){running=true;startedAt=SystemClock.uptimeMillis();invalidateSelf();scheduleSelf(this,startedAt+FRAME_MS);}}
 @Override public void stop(){if(running)stoppedAt=SystemClock.uptimeMillis();running=false;unscheduleSelf(this);}
 @Override public boolean isRunning(){return running;}
 @Override public void run(){if(running&&isVisible()){invalidateSelf();scheduleSelf(this,SystemClock.uptimeMillis()+FRAME_MS);}}
 @Override public boolean setVisible(boolean visible,boolean restart){
  boolean changed=super.setVisible(visible,restart);
  if(!visible)stop();else if(restart||changed){stop();start();}
  return changed;
 }
}
